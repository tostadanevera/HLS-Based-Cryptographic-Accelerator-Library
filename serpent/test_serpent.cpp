std::vector<u8> hex_to_bytes(const std::string& hex)
{
    std::vector<u8> out(hex.size() / 2);
    for (size_t i = 0; i < out.size(); i++)
        out[i] = static_cast<u8>(std::stoi(hex.substr(i * 2, 2), nullptr, 16));
    return out;
}

std::string bytes_to_hex(const std::vector<u8>& bytes)
{
    std::ostringstream oss;
    for (u8 byte : bytes) oss << std::hex << std::setw(2) << std::setfill('0') << static_cast<int>(byte);
    return oss.str();
}

