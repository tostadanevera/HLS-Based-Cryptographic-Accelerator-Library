// Round constants (as 32-bit words, MSB holds the constant byte)
constexpr u32 rcon[10] =
{
    0x01000000, 0x02000000, 0x04000000, 0x08000000, 0x10000000,
    0x20000000, 0x40000000, 0x80000000, 0x1B000000, 0x36000000
};

u32 bytes_to_word(const u8* bytes)
{
    return (static_cast<u32>(bytes[0]) << 24) | (static_cast<u32>(bytes[1]) << 16) |
           (static_cast<u32>(bytes[2]) << 8)  |  static_cast<u32>(bytes[3]);
}

void word_to_bytes(u32 word, u8* bytes)
{
    bytes[0] = (word >> 24) & 0xFF;
    bytes[1] = (word >> 16) & 0xFF;
    bytes[2] = (word >> 8)  & 0xFF;
    bytes[3] =  word        & 0xFF;
}

void add_round_key(std::array<u8, AES_STATE_SIZE>& state, const std::array<u8, AES_STATE_SIZE>& round_key)
{
    for (int i = 0; i < AES_STATE_SIZE; i++)
        state[i] ^= round_key[i];
}

void sub_bytes(std::array<u8, AES_STATE_SIZE>& state)
{
    for (int i = 0; i < AES_STATE_SIZE; i++)
        state[i] = s_box[state[i]];
}

void inv_sub_bytes(std::array<u8, AES_STATE_SIZE>& state)
{
    for (int i = 0; i < AES_STATE_SIZE; i++)
        state[i] = inv_s_box[state[i]];
}

void shift_rows(std::array<u8, AES_STATE_SIZE>& state)
{
    std::array<u8, AES_STATE_SIZE> t = state;

    t[1] = state[5];  t[5] = state[9];   t[9]  = state[13]; t[13] = state[1];
    t[2] = state[10]; t[6] = state[14];  t[10] = state[2];  t[14] = state[6];
    t[3] = state[15]; t[7] = state[3];   t[11] = state[7];  t[15] = state[11];

    state = t;
}

void inv_shift_rows(std::array<u8, AES_STATE_SIZE>& state)
{
    std::array<u8, AES_STATE_SIZE> t = state;

    t[5] = state[1];  t[9]  = state[5];  t[13] = state[9];  t[1] = state[13];
    t[10] = state[2]; t[14] = state[6];  t[2]  = state[10]; t[6] = state[14];
    t[15] = state[3]; t[3]  = state[7];  t[7]  = state[11]; t[11] = state[15];

    state = t;
}

u8 xtime(u8 x)
{
    return static_cast<u8>((x << 1) ^ ((x & 0x80) ? 0x1B : 0x00));
}

u8 mul2(u8 x) { return xtime(x); }
u8 mul3(u8 x) { return static_cast<u8>(xtime(x) ^ x); }

// Constant GF(2^8) multipliers for the inverse MixColumns matrix (0e, 0b, 0d, 09).
u8 mul9(u8 x)  { u8 x2 = xtime(x), x4 = xtime(x2), x8 = xtime(x4); return static_cast<u8>(x8 ^ x); }
u8 mul11(u8 x) { u8 x2 = xtime(x), x4 = xtime(x2), x8 = xtime(x4); return static_cast<u8>(x8 ^ x2 ^ x); }
u8 mul13(u8 x) { u8 x2 = xtime(x), x4 = xtime(x2), x8 = xtime(x4); return static_cast<u8>(x8 ^ x4 ^ x); }
u8 mul14(u8 x) { u8 x2 = xtime(x), x4 = xtime(x2), x8 = xtime(x4); return static_cast<u8>(x8 ^ x4 ^ x2); }

// Multiplies each column of the state by a fixed matrix in the finite field GF(2^8)
void mix_columns(std::array<u8, AES_STATE_SIZE>& state)
{
    std::array<u8, AES_STATE_SIZE> t;
#pragma HLS ARRAY_PARTITION variable=t complete dim=1

    for (int col = 0; col < 4; ++col)
    {
        int i = col * 4;
        u8 a0 = state[i], a1 = state[i + 1], a2 = state[i + 2], a3 = state[i + 3];

        t[i]     = mul2(a0) ^ mul3(a1) ^ a2 ^ a3;
        t[i + 1] = a0 ^ mul2(a1) ^ mul3(a2) ^ a3;
        t[i + 2] = a0 ^ a1 ^ mul2(a2) ^ mul3(a3);
        t[i + 3] = mul3(a0) ^ a1 ^ a2 ^ mul2(a3);
    }

    state = t;
}

void inv_mix_columns(std::array<u8, AES_STATE_SIZE>& state)
{
    std::array<u8, AES_STATE_SIZE> t;
#pragma HLS ARRAY_PARTITION variable=t complete dim=1

    for (int col = 0; col < 4; ++col)
    {
        int i = col * 4;
        u8 a0 = state[i], a1 = state[i + 1], a2 = state[i + 2], a3 = state[i + 3];

        t[i]     = mul14(a0) ^ mul11(a1) ^ mul13(a2) ^ mul9(a3);
        t[i + 1] = mul9(a0)  ^ mul14(a1) ^ mul11(a2) ^ mul13(a3);
        t[i + 2] = mul13(a0) ^ mul9(a1)  ^ mul14(a2) ^ mul11(a3);
        t[i + 3] = mul11(a0) ^ mul13(a1) ^ mul9(a2)  ^ mul14(a3);
    }

    state = t;
}

u32 rot_word(u32 word) { return (word << 8) | (word >> 24); }

// Apply S-Box to each byte
u32 sub_word(u32 word)
{
    u8 b[4];
    word_to_bytes(word, b);
    for (int i = 0; i < 4; i++) b[i] = s_box[b[i]];
    return bytes_to_word(b);
}

// Expands a 128-bit key into 11 round keys (176 bytes total)
std::array<u8, AES_EXPANDED_KEY_SIZE> key_expansion(const std::array<u8, AES_KEY_SIZE>& key)
{
    u32 w[44];  // 44 words, each 4 bytes
    std::array<u8, AES_EXPANDED_KEY_SIZE> expanded_key;

    for (int i = 0; i < 4; i++)
        w[i] = bytes_to_word(key.data() + i * 4);

    for (int i = 4; i < 44; i++)
    {
    #pragma HLS PIPELINE II=2
        u32 temp = w[i - 1];

        if (i % 4 == 0)
        {
            temp = rot_word(temp);
            temp = sub_word(temp);
            temp ^= rcon[(i / 4) - 1];
        }

        w[i] = w[i - 4] ^ temp;
    }

    for (int i = 0; i < 44; i++)
        word_to_bytes(w[i], expanded_key.data() + i * 4);

    return expanded_key;
}

std::array<u8, AES_STATE_SIZE> round_key_slice(const std::array<u8, AES_EXPANDED_KEY_SIZE>& expanded_key, int round)
{
    std::array<u8, AES_STATE_SIZE> rk;
#pragma HLS ARRAY_PARTITION variable=rk complete dim=1
    for (int j = 0; j < AES_STATE_SIZE; j++)
        rk[j] = expanded_key[round * AES_STATE_SIZE + j];
    return rk;
}

