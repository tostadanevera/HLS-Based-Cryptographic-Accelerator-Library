// AES encryption
void aes_encrypt(const std::array<u8, AES_STATE_SIZE>& plaintext,
                 const std::array<u8, AES_KEY_SIZE>&   key,
                 std::array<u8, AES_STATE_SIZE>&       ciphertext)
{
    std::array<u8, AES_STATE_SIZE> state = plaintext;
#pragma HLS ARRAY_PARTITION variable=state complete dim=1
    std::array<u8, AES_EXPANDED_KEY_SIZE> expanded_key = key_expansion(key);
#pragma HLS ARRAY_PARTITION variable=expanded_key complete dim=1

    add_round_key(state, round_key_slice(expanded_key, 0));

    for (int round = 1; round < AES_ROUNDS; round++)
    {
    #pragma HLS PIPELINE II=2
        sub_bytes(state);
        shift_rows(state);
        mix_columns(state);
        add_round_key(state, round_key_slice(expanded_key, round));
    }

    sub_bytes(state);
    shift_rows(state);
    add_round_key(state, round_key_slice(expanded_key, AES_ROUNDS));

    ciphertext = state;
}

// AES decryption
void aes_decrypt(const std::array<u8, AES_STATE_SIZE>& ciphertext,
                 const std::array<u8, AES_KEY_SIZE>&   key,
                 std::array<u8, AES_STATE_SIZE>&       plaintext)
{
    std::array<u8, AES_STATE_SIZE> state = ciphertext;
#pragma HLS ARRAY_PARTITION variable=state complete dim=1
    std::array<u8, AES_EXPANDED_KEY_SIZE> expanded_key = key_expansion(key);
#pragma HLS ARRAY_PARTITION variable=expanded_key complete dim=1

    add_round_key(state, round_key_slice(expanded_key, AES_ROUNDS));

    for (int round = AES_ROUNDS - 1; round > 0; round--)
    {
    #pragma HLS PIPELINE II=3
        inv_shift_rows(state);
        inv_sub_bytes(state);
        add_round_key(state, round_key_slice(expanded_key, round));
        inv_mix_columns(state);
    }

    inv_shift_rows(state);
    inv_sub_bytes(state);
    add_round_key(state, round_key_slice(expanded_key, 0));

    plaintext = state;
}