int main()
{
    int total = 0, passed = 0;

    std::cout << "Serpent tests\n\n";

    for (const auto& v : test_vectors)
    {
        total++;

        std::vector<u8> key = hex_to_bytes(v.key);
        std::vector<u8> plain = hex_to_bytes(v.plaintext);
        std::vector<u8> expected = hex_to_bytes(v.cipher);

        std::vector<u8> cipher(16);
        serpent_encrypt(plain.data(), key.data(), key.size(), cipher.data());

        std::vector<u8> decrypted(16);
        serpent_decrypt(cipher.data(), key.data(), key.size(), decrypted.data());

        bool enc_ok = (cipher == expected);
        bool dec_ok = (decrypted == plain);

        std::cout << "key_len=" << key.size() * 8 << "  ciphertext: " << bytes_to_hex(cipher)
                  << (enc_ok ? " [OK]" : " [FAIL]") << "\n";
        
        std::cout << "round-trip: " << (dec_ok ? "[OK]" : "[FAIL]") << "\n\n";

        if (enc_ok && dec_ok) passed++;
    }

    std::cout << "\n" << passed << "/" << total << " tests passed\n";
    return (passed == total) ? 0 : 1;
}