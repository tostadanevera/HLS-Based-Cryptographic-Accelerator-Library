{
    int total = 0, passed = 0;

    std::cout << "Serpent HLS wrapper tests" << std::endl;

    for (const auto& v : test_vectors)
    {
        total++;

        std::vector<u8> key_bytes = hex_to_bytes(v.key);
        std::vector<u8> plain = hex_to_bytes(v.plaintext);
        std::vector<u8> expected_cipher = hex_to_bytes(v.cipher);

        u8 key[SERPENT_MAX_KEY_WORDS * 4] = {0};
        std::memcpy(key, key_bytes.data(), key_bytes.size());

        u8 input[16], cipher_buf[16], decrypted_buf[16];
        std::memcpy(input, plain.data(), 16);

        int enc_rc = serpent_top(key, static_cast<u32>(key_bytes.size()), input, cipher_buf, 0);
        int dec_rc = serpent_top(key, static_cast<u32>(key_bytes.size()), cipher_buf, decrypted_buf, 1);

        bool enc_ok = (enc_rc == 0) && (std::memcmp(cipher_buf, expected_cipher.data(), 16) == 0);
        bool dec_ok = (dec_rc == 0) && (std::memcmp(decrypted_buf, plain.data(), 16) == 0);
        bool ok = enc_ok && dec_ok;

        std::cout << "key_len=" << key_bytes.size() * 8
                  << "  ciphertext: " << bytes_to_hex(cipher_buf, 16)
                  << (ok ? " [OK]" : " [FAIL]") << std::endl;
        if (!enc_ok)
            std::cout << "  encrypt expected: " << v.cipher << std::endl;
        if (!dec_ok)
            std::cout << "  decrypt mismatch" << std::endl;

        if (ok) passed++;
    }

    std::cout << passed << "/" << total << " tests passed" << std::endl;
    return (passed == total) ? 0 : 1;
}